import assert from "node:assert/strict";
import test from "node:test";
import { createMemoryPaymentRepository } from "../../src/lib/payments/repository";
import { applyPaymentEvent, createPaymentAccount, createPaymentRequest, getPublicPayment, startPayment, createRefund } from "../../src/lib/payments/service";
import type { PaymentProviderAdapter } from "../../src/lib/payments/types";

const COMPANY = "10000000-0000-4000-8000-000000000001";
const USER = "10000000-0000-4000-8000-000000000002";
const ORDER = "10000000-0000-4000-8000-000000000003";
const KEY = Buffer.alloc(32, 7).toString("base64url");

function adapter(): PaymentProviderAdapter {
  return { async createCheckout() { return { providerTransactionId: "pi_1", paymentUrl: "https://pay.example/1" }; }, async verifyWebhook() { return []; }, async refund() { return { providerRefundId: "re_1" }; } };
}

test("payment requests enforce order balance and expose only public fields", async () => {
  const repository = createMemoryPaymentRepository();
  repository.seedOrder({ id: ORDER, companyId: COMPANY, orderNo: "SO-1", totalAmount: "100.00", currency: "USD", paymentStatus: "unpaid", amountPaidMinor: 0, merchantName: "Demo" });
  const account = await createPaymentAccount(repository, COMPANY, { provider: "stripe", displayName: "Stripe", credentials: { secretKey: "sk_test", publishableKey: "pk_test", webhookSecret: "whsec_test" } }, KEY);
  assert.equal(account.credentialsConfigured, true);
  const result = await createPaymentRequest(repository, { companyId: COMPANY, userId: USER, orderId: ORDER, amount: "30.00", currency: "USD" });
  const publicView = await getPublicPayment(repository, result.token);
  assert.equal(publicView?.amountMinor, 3000);
  assert.equal("companyId" in (publicView || {}), false);
  assert.equal("publicTokenHash" in (publicView || {}), false);
  await assert.rejects(() => createPaymentRequest(repository, { companyId: COMPANY, userId: USER, orderId: ORDER, amount: "101.00", currency: "USD" }), /exceeds/i);
  let checkoutUrl = "";
  const checkoutAdapter = adapter();
  checkoutAdapter.createCheckout = async (input) => {
    checkoutUrl = input.successUrl;
    return { providerTransactionId: "pi_1", paymentUrl: "https://pay.example/1" };
  };
  const attempt = await startPayment(repository, { request: result.request, publicToken: result.token, account, adapter: checkoutAdapter, idempotencyKey: "attempt-1", baseUrl: "https://tradepilot.example" });
  assert.equal(attempt?.status, "requires_action");
  assert.equal(checkoutUrl, `https://tradepilot.example/pay/${result.token}`);
  assert.equal(checkoutUrl.includes(result.request.publicTokenHash), false);
  const same = await startPayment(repository, { request: result.request, publicToken: result.token, account, adapter: adapter(), idempotencyKey: "attempt-1", baseUrl: "https://tradepilot.example" });
  assert.equal(same?.id, attempt?.id);
});

