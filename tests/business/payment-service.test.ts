  const attempt = await startPayment(repository, { request: request.request, publicToken: request.token, account, adapter: adapter(), idempotencyKey: "attempt-refund", baseUrl: "https://tradepilot.example" });
  await repository.updateAttempt(COMPANY, attempt!.id, { status: "paid", providerTransactionId: "pi_1" });
